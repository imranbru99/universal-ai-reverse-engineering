from __future__ import annotations

import json
import zipfile
from pathlib import Path
from typing import Any


def generate_independent_project(
    output_dir: Path,
    *,
    project_name: str,
    entities: list[dict[str, Any]],
    states: list[dict[str, Any]],
) -> Path:
    """Generate an independent Next.js + FastAPI + PostgreSQL project (no proprietary assets)."""
    root = output_dir / "reconstructed-app"
    if root.exists():
        # clean lightweight
        for p in root.rglob("*"):
            if p.is_file():
                p.unlink()
    (root / "apps" / "web").mkdir(parents=True, exist_ok=True)
    (root / "apps" / "api").mkdir(parents=True, exist_ok=True)
    (root / "docs").mkdir(parents=True, exist_ok=True)

    entity_names = [e["name"] for e in entities]
    readme = f"""# {project_name} (Independent Reconstruction)

This application was generated by REVERSEFORGE AI from **authorized observed evidence**.

## Classification notice

- UI routes mirror *observed* navigation where confidence was high.
- Database schema fields are **INFERRED** unless marked USER_CONFIRMED.
- No proprietary brands, assets, or credentials are included.

## Stack

- Frontend: Next.js (App Router) static-friendly pages
- Backend: FastAPI
- Database: PostgreSQL (SQLAlchemy models + SQL migration sketch)

## Run locally

```bash
# API
cd apps/api
python -m venv .venv
source .venv/bin/activate  # Windows: .venv\\\\Scripts\\\\activate
pip install -r requirements.txt
uvicorn main:app --reload --port 8080

# Web
cd apps/web
npm install
npm run dev -- --port 3080
```

## Observed screens (source analysis)

{chr(10).join(f"- {s.get('title') or s.get('url')} ({s.get('url')})" for s in states[:20])}

## Proposed entities

{chr(10).join(f"- {n}" for n in entity_names)}
"""
    (root / "README.md").write_text(readme, encoding="utf-8")

    (root / "docs" / "PROVENANCE.md").write_text(
        "All schema elements are INFERRED unless reviewed.\n"
        "Do not treat this as the original private schema.\n",
        encoding="utf-8",
    )

    # API
    models_src = ["from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column", "from sqlalchemy import String, Integer, Boolean", "", "class Base(DeclarativeBase):", "    pass", ""]
    for e in entities:
        models_src.append(f"class {e['name']}(Base):")
        models_src.append(f"    __tablename__ = '{e['name'].lower()}s'")
        models_src.append("    id: Mapped[int] = mapped_column(Integer, primary_key=True)")
        for f in e.get("fields", []):
            typ = "String(200)" if f.get("data_type") != "integer" else "Integer"
            models_src.append(f"    {f['name']}: Mapped[{'int' if typ=='Integer' else 'str'}] = mapped_column({typ})")
        models_src.append("")

    (root / "apps" / "api" / "models.py").write_text("\n".join(models_src), encoding="utf-8")
    (root / "apps" / "api" / "requirements.txt").write_text(
        "fastapi==0.115.6\nuvicorn==0.34.0\nsqlalchemy==2.0.36\npydantic==2.10.3\npytest==8.3.4\n",
        encoding="utf-8",
    )
    (root / "apps" / "api" / "main.py").write_text(
        '''from fastapi import FastAPI
from pydantic import BaseModel

app = FastAPI(title="Independent Reconstruction API")

class Health(BaseModel):
    status: str

@app.get("/health", response_model=Health)
def health():
    return Health(status="ok")

@app.get("/api/meta/entities")
def entities():
    return '''
        + json.dumps([{"name": e["name"], "fields": e.get("fields", [])} for e in entities])
        + '''
''',
        encoding="utf-8",
    )
    (root / "apps" / "api" / "test_health.py").write_text(
        "from fastapi.testclient import TestClient\nfrom main import app\n\nclient = TestClient(app)\n\ndef test_health():\n    assert client.get('/health').json()['status'] == 'ok'\n",
        encoding="utf-8",
    )
    (root / "apps" / "api" / "migrations" / "001_init.sql").parent.mkdir(parents=True, exist_ok=True)
    sql_lines = ["-- INFERRED schema proposal — not the original private schema"]
    for e in entities:
        cols = ["id SERIAL PRIMARY KEY"]
        for f in e.get("fields", []):
            sql_t = "INTEGER" if f.get("data_type") == "integer" else "TEXT"
            null_sql = "" if not f.get("nullable", True) else ""
            cols.append(f"{f['name']} {sql_t}{null_sql}")
        sql_lines.append(f"CREATE TABLE IF NOT EXISTS {e['name'].lower()}s (\n  " + ",\n  ".join(cols) + "\n);")
    (root / "apps" / "api" / "migrations" / "001_init.sql").write_text("\n\n".join(sql_lines), encoding="utf-8")

    # Web — independent branding
    (root / "apps" / "web" / "package.json").write_text(
        json.dumps(
            {
                "name": "reconstructed-web",
                "private": True,
                "scripts": {"dev": "npx serve -l 3080 .", "test": "node ./smoke.js"},
                "dependencies": {"serve": "14.2.4"},
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    pages = "\n".join(
        f'<li><a href="{s.get("url", "#")}">{s.get("title") or s.get("url")}</a> '
        f'<span data-class=\"{s.get("classification", "OBSERVED")}\">observed</span></li>'
        for s in states[:15]
    )
    (root / "apps" / "web" / "index.html").write_text(
        f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8"/>
  <title>{project_name} — Independent UI</title>
  <style>
    :root {{ --bg:#f6f4ef; --ink:#1c1a16; --accent:#0f6b5c; }}
    body {{ margin:0; font-family: "Segoe UI", sans-serif; background:linear-gradient(160deg,#f6f4ef,#e7eef0); color:var(--ink); }}
    main {{ max-width:960px; margin:0 auto; padding:48px 24px; }}
    h1 {{ font-size:2.4rem; letter-spacing:-0.03em; }}
    .note {{ color:#555; max-width:40rem; }}
    .badge {{ display:inline-block; border:1px solid #aaa; padding:2px 8px; font-size:12px; }}
  </style>
</head>
<body>
  <main>
    <p class="badge">INDEPENDENT RECONSTRUCTION</p>
    <h1>{project_name}</h1>
    <p class="note">Generated without copying proprietary brands or assets. Screen inventory below is evidence-linked and classified.</p>
    <h2>Observed screens</h2>
    <ul>{pages}</ul>
    <h2>Proposed domain</h2>
    <ul>{''.join(f'<li>{n} <em>(INFERRED)</em></li>' for n in entity_names)}</ul>
  </main>
</body>
</html>
""",
        encoding="utf-8",
    )
    (root / "apps" / "web" / "smoke.js").write_text(
        "const fs=require('fs'); const html=fs.readFileSync('index.html','utf8'); if(!html.includes('INDEPENDENT RECONSTRUCTION')) process.exit(1); console.log('ok');\n",
        encoding="utf-8",
    )

    zip_path = output_dir / f"{project_name.replace(' ', '_').lower()}_export.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for file in root.rglob("*"):
            if file.is_file():
                zf.write(file, file.relative_to(output_dir).as_posix())
    return zip_path
